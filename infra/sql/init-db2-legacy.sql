-- IBM DB2 Core Settlement Ledger Schema
CREATE TABLE LEGACY_CORE_LEDGER (
    LEDGER_SEQ_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 100000, INCREMENT BY 1),
    TX_REFERENCE_CODE CHAR(36) NOT NULL,
    SOURCE_IBAN VARCHAR(34) NOT NULL,
    TARGET_IBAN VARCHAR(34) NOT NULL,
    AMOUNT DECIMAL(19, 4) NOT NULL,
    CURRENCY CHAR(3) NOT NULL,
    BOOKING_DATE TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    AUDIT_STATUS CHAR(12) NOT NULL,
    MAINFRAME_BATCH_ID VARCHAR(24),
    PRIMARY KEY (LEDGER_SEQ_ID)
);

CREATE INDEX IDX_DB2_TX_REF ON LEGACY_CORE_LEDGER(TX_REFERENCE_CODE);
CREATE INDEX IDX_DB2_BOOKING_DT ON LEGACY_CORE_LEDGER(BOOKING_DATE);
